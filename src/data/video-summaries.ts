/**
 * Arabic video-first content model.
 *
 * Each entry pairs an embeddable official YouTube video (summary, AMV or short
 * review) with a 2–3 paragraph Arabic write-up written for search, plus the
 * licensed platform the visitor should finish the episode on. No hosted video,
 * no pirated sources — the CTA always points at the official platform.
 */
export type VideoKind = "summary" | "amv" | "review";

export type VideoSummary = {
  animeSlug: string;
  kind: VideoKind;
  youtubeId: string;
  /** Arabic headline shown above the embed. */
  titleAr: string;
  /** 2–3 Arabic paragraphs rendered under the player for SEO. */
  paragraphsAr: string[];
};

export const KIND_LABEL_AR: Record<VideoKind, string> = {
  summary: "ملخص الأنمي",
  amv: "فيديو موسيقي AMV",
  review: "مراجعة سريعة",
};

/** Licensed platform used by the "watch full episode" CTA. */
const PLATFORMS: Record<string, { label: string; labelAr: string; search: string }> = {
  crunchyroll: { label: "Crunchyroll", labelAr: "كranchyroll", search: "https://www.crunchyroll.com/search?q=" },
  netflix: { label: "Netflix", labelAr: "نتفليكس", search: "https://www.netflix.com/search?q=" },
};

const PLATFORM_BY_SLUG: Record<string, keyof typeof PLATFORMS> = {
  "attack-on-titan": "netflix",
  "spy-x-family": "netflix",
};

export function officialPlatformFor(slug: string, title: string) {
  const key = PLATFORM_BY_SLUG[slug] ?? "crunchyroll";
  const p = PLATFORMS[key];
  return {
    label: p.label,
    url: `${p.search}${encodeURIComponent(title)}`,
  };
}

